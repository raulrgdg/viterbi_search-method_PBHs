ALL_PACKS = tuple(sorted(PACK_WINDOWS))
PAPER_PACKS = tuple(range(1, 109))  # the packs of arXiv:2607.18352


def pack_window(pack):
    """Return (gps_start, gps_end) of an O3b pack, validating the pack id."""
    try:
        return PACK_WINDOWS[int(pack)]
    except KeyError:
        raise ValueError(f"Unknown O3b pack {pack}; valid packs are 1..{max(ALL_PACKS)}.") from None


def parse_pack_list(text):
    """Parse 'all', '5', '1,2,7' or '1-12,37-48' into a sorted list of pack ids."""
    text = str(text).strip().lower()
    if text == "all":
        return list(ALL_PACKS)
    packs = set()
    for token in filter(None, (t.strip() for t in text.split(","))):
        if "-" in token:
            first, last = (int(v) for v in token.split("-", 1))
            packs.update(range(first, last + 1))
        else:
            packs.add(int(token))
    for pack in packs:
        pack_window(pack)
    return sorted(packs)


def _check_windows():
    for pack, (start, end) in PACK_WINDOWS.items():
        if end - start != PACK_DURATION:
            raise ValueError(f"Pack {pack} does not span {PACK_DURATION} s.")


_check_windows()
